def type_note(t: str) -> str:
    if t not in TYPES:
        return ""
    name, n, how, done, *_ = TYPES[t]
    out = f"\n\n（这类问题是「{name}」：{how}；关键说法至少 {n} 个独立来源；{done}就算答完。）"
    if t == "judge":
        out += "\n\n" + JUDGE_HOW
    elif t == "buy":
        out += "\n\n" + BUY_HOW
    return out


